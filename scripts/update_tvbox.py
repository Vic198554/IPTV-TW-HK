    ("台湾", "三立 SET NEWS", "https://www.youtube.com/watch?v=yeYC0mbSIOo"),
    ("台湾", "三立iNEWS", "https://www.youtube.com/live/pF507BLtbqU"),
    ("台湾", "台湾公共电视 PTS", "https://www.youtube.com/watch?v=quwqlazU-c8"),
    ("台湾", "公视台语台", "https://www.youtube.com/watch?v=6KlRR_DGhmI"),
    ("台湾", "华视 CTS", "https://www.youtube.com/watch?v=wM0g8EoUZ_E"),
    ("台湾", "台湾电视公司 TTV", "https://www.youtube.com/watch?v=9iRAqBMakXY"),
