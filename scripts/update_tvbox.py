#!/usr/bin/env python3
"""Generate TVBox-compatible playlists from YouTube live channels.

For each YouTube live URL, yt-dlp is used to get the HLS *variant*
manifest URL (formats[].manifest_url). That manifest is a master
playlist containing both video and audio variants, so a single URL
works in ExoPlayer-based players such as TVBox white box, unlike the
separate video-only / audio-only hls_playlist URLs.

If extraction fails for a channel, the previous URL from the existing
tvbox.m3u8 (if present) is kept, so one failure does not empty the list.
"""
import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

